export type AreaUnit = "ha" | "are" | "acre";

export const AREA_UNITS: { id: AreaUnit; labelKey: string; ha: number }[] = [
  { id: "ha", labelKey: "inp.ha", ha: 1 },
  { id: "are", labelKey: "inp.are", ha: 0.01 },
  { id: "acre", labelKey: "inp.acre", ha: 0.404686 },
];

export const toHectares = (value: number, unit: AreaUnit): number =>
  Math.max(0, value) * (AREA_UNITS.find((u) => u.id === unit)?.ha ?? 1);